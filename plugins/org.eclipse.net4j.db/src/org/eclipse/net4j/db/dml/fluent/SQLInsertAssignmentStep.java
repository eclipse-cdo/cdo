package org.eclipse.net4j.db.dml.fluent;

import org.eclipse.net4j.db.dml.SQLExpression;

/**
 * An INSERT assignment whose value must be supplied before further assignments or completion.
 *
 * @author Eike Stepper
 * @since 4.15
 * @noimplement This interface is not intended to be implemented by clients.
 * @noextend This interface is not intended to be extended by clients.
 */
public interface SQLInsertAssignmentStep
{
  /**
   * Completes the pending assignment with an expression value.
   *
   * @param value the expression assigned to the column
   * @return the next valid fluent stage
   * @since 4.15
   */
  public SQLInsertSetStep to(SQLExpression value);
}
